#!/usr/bin/env node
/**
 * Writes docs/aval/SPECIALIST_READINESS.md from the catalogue: every
 * Specialist's derived contract — required and optional capabilities,
 * approval classes, and whether it is complete, analysis-only or incomplete.
 *
 * Generated, never hand-edited: the rules live in
 * lib/agents/organization/contract.ts, and this file only reports them.
 *
 *   node scripts/specialist-readiness.mjs
 */
import { writeFileSync } from "node:fs";
import { LEADS, specialistsForDomain } from "../lib/agents/organization/index.ts";
import { specialistContract } from "../lib/agents/organization/contract.ts";

const lines = [
  "# Specialist readiness",
  "",
  "Generated by `scripts/specialist-readiness.mjs` from `lib/agents/organization/contract.ts`. Do not edit by hand.",
  "",
  "- **complete**: every required capability has an implemented tool.",
  "- **analysis-only**: nothing required is missing except proposals a person acts on (prepare, review, recommend, draft); the Specialist's product is analysis or a draft.",
  "- **incomplete**: a required read or act has no tool yet; the missing capabilities are listed.",
  "",
  "Internal only. Readiness is never shown in customer UI.",
  "",
];
const totals = { complete: 0, analysis_only: 0, incomplete: 0 };
for (const lead of LEADS) {
  const rows = specialistsForDomain(lead.domain).map((specialist) => ({ specialist, contract: specialistContract(specialist) }));
  for (const { contract } of rows) totals[contract.readiness]++;
  lines.push(`## ${lead.name}`, "", "| Specialist | Readiness | Required | Optional | Approval classes | Missing |", "|---|---|---|---|---|---|");
  for (const { specialist, contract } of rows) {
    lines.push(`| ${specialist.name} | ${contract.readiness.replace("_", "-")} | ${contract.required.join(", ")} | ${contract.optional.join(", ") || "—"} | ${contract.approvalClasses.join(", ") || "—"} | ${contract.missing.join(", ") || "—"} |`);
  }
  lines.push("");
}
lines.splice(10, 0, `**Totals:** ${totals.complete} complete, ${totals.analysis_only} analysis-only, ${totals.incomplete} incomplete (of ${totals.complete + totals.analysis_only + totals.incomplete}).`, "");
writeFileSync(new URL("../docs/aval/SPECIALIST_READINESS.md", import.meta.url), lines.join("\n") + "\n");
console.log(totals);
