#!/usr/bin/env node
/**
 * Writes docs/aval/SPECIALIST_READINESS.md from the catalogue: every
 * Specialist's derived contract — required and optional capabilities,
 * approval classes, what it executes, its readiness, and for an analysis-only
 * Specialist the analysis contract it is held to.
 *
 * Generated, never hand-edited: the rules live in
 * lib/agents/organization/contract.ts, and this file only reports them.
 *
 *   node scripts/specialist-readiness.mjs
 */
import { writeFileSync } from "node:fs";
import { LEADS, specialistsForDomain } from "../lib/agents/organization/index.ts";
import { specialistContract } from "../lib/agents/organization/contract.ts";

const LABEL = { EXECUTION_READY: "execution-ready", ANALYSIS_ONLY_READY: "analysis-only-ready", INCOMPLETE: "incomplete" };
const lines = [
  "# Specialist readiness",
  "",
  "Generated by `scripts/specialist-readiness.mjs` from `lib/agents/organization/contract.ts`. Do not edit by hand.",
  "",
  "- **execution-ready**: every required capability is met and at least one act has an implemented tool; it changes something, under policy and approval.",
  "- **analysis-only-ready**: every required capability is met and it executes nothing. Its product is evidence-backed analysis or a proposal a person acts on. This is a design, not a gap; each one's analysis contract is listed below.",
  "- **incomplete**: a required read or act has no implemented tool yet; the missing capabilities are listed. Why each is missing is in `SPECIALIST_REQUIREMENT_AUDIT.md`.",
  "",
  "Readiness says what the code can do. It is not provider validation: no Specialist here has been exercised against a live provider tenant.",
  "",
  "Internal only. Readiness is never shown in customer UI.",
  "",
];
const totals = { EXECUTION_READY: 0, ANALYSIS_ONLY_READY: 0, INCOMPLETE: 0 };
const analysisSections = [];
for (const lead of LEADS) {
  const rows = specialistsForDomain(lead.domain).map((specialist) => ({ specialist, contract: specialistContract(specialist) }));
  for (const { contract } of rows) totals[contract.readiness]++;
  lines.push(`## ${lead.name}`, "", "| Specialist | Readiness | Required | Optional | Executes | Approval classes | Missing |", "|---|---|---|---|---|---|---|");
  for (const { specialist, contract } of rows) {
    lines.push(`| ${specialist.name} | ${LABEL[contract.readiness]} | ${contract.required.join(", ")} | ${contract.optional.join(", ") || "—"} | ${contract.executes.join(", ") || "—"} | ${contract.approvalClasses.join(", ") || "—"} | ${contract.missing.join(", ") || "—"} |`);
    if (contract.analysis) {
      const a = contract.analysis;
      analysisSections.push(
        `### ${specialist.name} (\`${specialist.id}\`)`,
        "",
        `- **Evidence it may read:** ${a.evidence.capabilities.join(", ") || "only what its Lead hands it"}${a.evidence.tools.length ? ` via ${a.evidence.tools.map((tool) => `\`${tool}\``).join(", ")}` : ""}.`,
        ...(a.unavailableEvidence.length ? [`- **Declared but unreadable today (stated, never guessed):** ${a.unavailableEvidence.join(", ")}.`] : []),
        `- **Returns:** ${a.returns.join("; ")}.`,
        `- **Consumed by:** \`${a.consumer.lead}\`, which returns it to Aval One${a.consumer.approvals.length ? `; proposals go to an authorized person (${a.consumer.approvals.join(", ")})` : ""}.`,
        `- **Forbidden to execute:** ${a.forbiddenToExecute.join("; ")}.`,
        `- **Done when:** ${a.completion.doneWhen} **Not done when:** ${a.completion.notDoneWhen}`,
        "",
      );
    }
  }
  lines.push("");
}
lines.splice(12, 0, `**Totals:** ${totals.EXECUTION_READY} execution-ready, ${totals.ANALYSIS_ONLY_READY} analysis-only-ready, ${totals.INCOMPLETE} incomplete (of ${totals.EXECUTION_READY + totals.ANALYSIS_ONLY_READY + totals.INCOMPLETE}).`, "");
lines.push("## Analysis contracts", "", "Every analysis-only-ready Specialist, with what it may read, what it returns, who consumes it and what it must never execute. The evaluation suite asserts each one is offered no mutating tool.", "", ...analysisSections);
writeFileSync(new URL("../docs/aval/SPECIALIST_READINESS.md", import.meta.url), lines.join("\n") + "\n");
console.log(totals);
